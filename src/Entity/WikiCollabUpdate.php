<?php

declare(strict_types=1);

namespace Nowo\WikiBundle\Entity;

use DateTimeImmutable;
use Doctrine\ORM\Mapping as ORM;

/**
 * One entry of the Yjs log of a page (1.13): an update a client posted (`kind` update) or a full-state snapshot a
 * client posted to compact the log (`kind` snapshot, covering every entry up to `covers_seq`). The auto-increment id is
 * the sequence number the clients see. Data is base64, exactly as the client sent it; the server never decodes Yjs.
 */
#[ORM\Entity]
#[ORM\Table(name: 'wiki_page_collab_updates')]
#[ORM\Index(name: 'wiki_collab_update_page', columns: ['page_id', 'id'])]
class WikiCollabUpdate
{
    public const KIND_UPDATE = 'update';

    public const KIND_SNAPSHOT = 'snapshot';

    #[ORM\Column(name: 'created_at', type: 'datetime_immutable')]
    private DateTimeImmutable $createdAt;

    /**
     * @param string $pageId id of the page
     * @param string $kind {@see self::KIND_UPDATE} or {@see self::KIND_SNAPSHOT}
     * @param string $data base64 Yjs update
     * @param int|null $coversSeq last sequence number a snapshot covers
     * @param int|null $id sequence number (null: generated by the database on flush)
     */
    public function __construct(
        #[ORM\Column(name: 'page_id', type: 'string', length: 36)]
        private string $pageId,
        #[ORM\Column(name: 'kind', type: 'string', length: 16)]
        private string $kind,
        #[ORM\Column(name: 'data', type: 'text')]
        private string $data,
        #[ORM\Column(name: 'covers_seq', type: 'integer', nullable: true)]
        private ?int $coversSeq = null,
        #[ORM\Id]
        #[ORM\GeneratedValue]
        #[ORM\Column(type: 'integer')]
        private ?int $id = null,
    ) {
        $this->createdAt = new DateTimeImmutable();
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getPageId(): string
    {
        return $this->pageId;
    }

    public function getKind(): string
    {
        return $this->kind;
    }

    public function getData(): string
    {
        return $this->data;
    }

    public function getCoversSeq(): ?int
    {
        return $this->coversSeq;
    }

    public function getCreatedAt(): DateTimeImmutable
    {
        return $this->createdAt;
    }
}
