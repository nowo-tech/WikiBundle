<?php

declare(strict_types=1);

namespace Nowo\WikiBundle\Tests\Unit\Resources;

use PHPUnit\Framework\TestCase;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use Symfony\Component\Yaml\Yaml;

use function dirname;
use function is_array;
use function sprintf;
use function strlen;

use const PREG_SET_ORDER;

/**
 * 1.38.1: a translation key used by a template or a form type must exist in the default locale. The locale parity
 * check (scripts/check-translation-parity.php) only compares the catalogues with each other, so a key missing from
 * all seven (`wiki_page_form.icon.placeholder`, generated by FormKit's `auto_placeholder` convention) passed it.
 */
final class TranslationKeysUsedExistTest extends TestCase
{
    /** @var array<string, true>|null */
    private static ?array $keys = null;

    public function testLiteralKeysOfTemplatesAndFormTypesExist(): void
    {
        $root    = dirname(__DIR__, 3) . '/src';
        $missing = [];
        foreach ([$root . '/Resources/views', $root . '/Form'] as $dir) {
            foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, RecursiveDirectoryIterator::SKIP_DOTS)) as $file) {
                if (!preg_match('/\.(twig|php)$/', (string) $file)) {
                    continue;
                }
                $source = (string) file_get_contents((string) $file);
                if (preg_match_all('/[\'"](wiki(?:_page_form)?\.[a-z0-9_]+(?:\.[a-z0-9_]+)+)[\'"]/', $source, $m) === false) {
                    continue;
                }
                foreach ($m[1] as $key) {
                    if (!isset($this->keys()[$key])) {
                        $missing[$key] = substr((string) $file, strlen($root) + 1);
                    }
                }
            }
        }
        self::assertSame([], $missing, 'Keys used but missing from NowoWikiBundle.en.yaml: ' . json_encode($missing));
    }

    public function testPageFormConventionKeysExist(): void
    {
        $source = (string) file_get_contents(dirname(__DIR__, 3) . '/src/Form/WikiPageFormType.php');
        self::assertGreaterThan(0, preg_match_all('/add(?:Text|Typed)Field\(\s*\'(\w+)\'\s*,\s*(?:(\w+)::class)?/', $source, $m, PREG_SET_ORDER));
        $missing = [];
        foreach ($m as $match) {
            if (($match[2] ?? '') === 'HiddenType') {
                continue;
            }
            $key = sprintf('wiki_page_form.%s.placeholder', $match[1]);
            if (!isset($this->keys()[$key])) {
                $missing[] = $key;
            }
        }
        self::assertSame([], $missing, 'FormKit auto_placeholder keys missing from the default locale');
    }

    /**
     * @return array<string, true>
     */
    private function keys(): array
    {
        if (self::$keys === null) {
            $parsed     = Yaml::parseFile(dirname(__DIR__, 3) . '/src/Resources/translations/NowoWikiBundle.en.yaml');
            self::$keys = [];
            self::flatten(is_array($parsed) ? $parsed : [], '');
        }

        return self::$keys;
    }

    /**
     * @param array<mixed> $tree
     */
    private static function flatten(array $tree, string $prefix): void
    {
        foreach ($tree as $key => $value) {
            $path = $prefix === '' ? (string) $key : $prefix . '.' . $key;
            if (is_array($value)) {
                self::flatten($value, $path);
            } else {
                self::$keys[$path] = true;
            }
        }
    }
}
